using System.Text;
using System.Text.Json.Nodes;
using Bobcat.Rendering;
using Bobcat.Ui.ResultsPages;

namespace Bobcat.Console.LivingDocs;

/// <summary>
/// Living documentation from results files (bobcat#553): one Markdown page per specification, an
/// index per feature and one for the run, the folded results as <c>results.json</c> and the
/// <c>&lt;bobcat-spec&gt;</c> script beside them — Storyteller's <c>dotnet stdocs</c>, over the
/// JSON results file (bobcat#540).
/// </summary>
/// <remarks>
/// <para>
/// <b>Written by the tool, rendered by core.</b> <see cref="MarkdownSpecText"/> renders a scenario
/// from the <see cref="SpecRender"/> that <see cref="ResultsFileReader"/> reads back, so the page
/// says what the console said. What lives here is the file layout: slugs, the fold of several
/// files into one run, attempts, the indexes and what is cleaned up.
/// </para>
/// <para>
/// <b>Deterministic and idempotent.</b> Running twice over the same results writes byte-identical
/// files, and nothing here reads a clock. A file whose content has not changed is not rewritten,
/// so a documentation build watching the directory sees no change.
/// </para>
/// <para>
/// <b>Stale pages are removed — only the ones this command wrote.</b> Every generated file starts
/// with <see cref="Marker"/>; a Markdown file under the output directory carrying it that this run
/// did not write is a specification that no longer exists, and is deleted. A file without the
/// marker is somebody's and is never touched, so <c>--out docs/specs</c> inside a documentation
/// tree is safe.
/// </para>
/// <para>
/// <b>Attachments stay files</b>, linked from each page relative to the page itself (the rule
/// Markdown and GitHub read links by), into the results directory they were written to — keep the
/// two together when publishing. When the results directory was not kept, an attachment is named
/// and linked to nothing, as the HTML results page does.
/// </para>
/// </remarks>
internal static class ResultsDocs
{
    /// <summary>The first line of every generated file. What <see cref="Write"/> owns, and may delete.</summary>
    public const string Marker = "<!-- Generated by `bobcat results-docs` from a Bobcat results file. Edits here are overwritten. -->";

    /// <summary>The folded results the web component reads, in the HTML results page's data shape.</summary>
    public const string ResultsFileName = "results.json";

    public const string IndexFileName = "index.md";

    /// <summary>The feature name a scenario with no feature is grouped under, as the results page groups it.</summary>
    public const string NoFeatureTitle = "Specifications";

    /// <summary>
    /// Write the documentation for <paramref name="resultsFiles"/> into <paramref name="outDirectory"/>.
    /// </summary>
    /// <param name="resultsFiles">The results files, as <see cref="ResultsPage.ResultsFilesIn"/> lists them.</param>
    /// <param name="outDirectory">Where the pages go. Created when missing.</param>
    /// <param name="attachmentsKept">Whether the results directories outlive this write, so attachments can be linked.</param>
    /// <param name="embedScript">The <c>bobcat-spec.js</c> text, or null to write none.</param>
    public static ResultsDocsOutcome Write(IReadOnlyList<string> resultsFiles, string outDirectory, bool attachmentsKept, string? embedScript)
    {
        var @out = Path.GetFullPath(outDirectory);
        Directory.CreateDirectory(@out);

        var files = resultsFiles
            .Select(ResultsFileReader.ReadFile)
            .OrderBy(x => x.FinishedAt)
            .ThenBy(x => x.Path, StringComparer.Ordinal)
            .ToList();

        var features = fold(files);
        var written = new List<string>();

        void write(string path, string content)
        {
            Directory.CreateDirectory(Path.GetDirectoryName(path)!);
            var bytes = new UTF8Encoding(false).GetBytes(content);
            if (!File.Exists(path) || !File.ReadAllBytes(path).AsSpan().SequenceEqual(bytes)) File.WriteAllBytes(path, bytes);
            written.Add(path);
        }

        foreach (var feature in features)
        {
            var directory = Path.Combine(@out, feature.Slug);

            foreach (var spec in feature.Specifications)
            {
                write(Path.Combine(directory, spec.Slug + ".md"), specificationPage(spec, directory, attachmentsKept));
            }

            write(Path.Combine(directory, IndexFileName), featureIndex(feature));
        }

        write(Path.Combine(@out, IndexFileName), runIndex(files, features));
        write(Path.Combine(@out, ResultsFileName), foldedResults(files, @out, attachmentsKept));
        if (embedScript is not null) write(Path.Combine(@out, SpecEmbed.FileName), embedScript);

        var removed = removeStale(@out, written);

        return new ResultsDocsOutcome(@out, written, removed, features.Count, features.Sum(f => f.Specifications.Count), files.Count);
    }

    /// <summary>
    /// The file name a title takes: lower case, letters and digits kept, every other run of characters
    /// one <c>-</c>, trimmed, at most 100 characters; <c>spec</c> for a title with nothing to keep.
    /// </summary>
    public static string Slug(string title)
    {
        var builder = new StringBuilder(title.Length);
        var dash = false;
        foreach (var c in title.Trim().ToLowerInvariant())
        {
            if (char.IsLetterOrDigit(c))
            {
                builder.Append(c);
                dash = false;
            }
            else if (!dash && builder.Length > 0)
            {
                builder.Append('-');
                dash = true;
            }
        }

        var slug = builder.ToString().TrimEnd('-');
        if (slug.Length > 100) slug = slug[..100].TrimEnd('-');
        return slug.Length == 0 ? "spec" : slug;
    }

    /// <summary>
    /// Slugs for <paramref name="titles"/> in order, no two alike: the second title whose slug is
    /// taken gets <c>-2</c>, the third <c>-3</c>. Deterministic for the same titles in the same order.
    /// </summary>
    internal static IReadOnlyList<string> Slugs(IReadOnlyList<string> titles)
    {
        var taken = new HashSet<string>(StringComparer.Ordinal);
        var slugs = new List<string>();
        foreach (var title in titles)
        {
            var slug = Slug(title);
            var unique = slug;
            for (var n = 2; !taken.Add(unique); n++) unique = $"{slug}-{n}";
            slugs.Add(unique);
        }

        return slugs;
    }

    /// <summary>
    /// Every scenario of every file as one run: by feature, then by title, each specification with
    /// its attempts oldest first (a supervised run writes one file per worker request, so a retried
    /// specification is in several).
    /// </summary>
    private static List<DocsFeature> fold(IReadOnlyList<ResultsFileContents> files)
    {
        var attempts = new Dictionary<string, List<DocsAttempt>>(StringComparer.Ordinal);
        foreach (var file in files)
        {
            foreach (var spec in file.Scenarios)
            {
                var identity = ResultsFileReader.IdentityOf(spec);
                if (!attempts.TryGetValue(identity, out var list)) attempts[identity] = list = new List<DocsAttempt>();
                list.Add(new DocsAttempt(spec, file));
            }
        }

        var byFeature = attempts
            .GroupBy(x => x.Value[0].Spec.FeatureTitle ?? "", StringComparer.Ordinal)
            .OrderBy(g => g.Key, StringComparer.Ordinal)
            .ToList();

        var featureSlugs = Slugs(byFeature.Select(g => g.Key.Length == 0 ? NoFeatureTitle : g.Key).ToList());

        var features = new List<DocsFeature>();
        for (var i = 0; i < byFeature.Count; i++)
        {
            var group = byFeature[i];
            var ordered = group.OrderBy(x => x.Value[0].Spec.Title, StringComparer.Ordinal).ThenBy(x => x.Key, StringComparer.Ordinal).ToList();
            var slugs = Slugs(ordered.Select(x => x.Value[0].Spec.Title).ToList());

            var specs = ordered.Select((entry, j) => new DocsSpecification(entry.Key, slugs[j], entry.Value)).ToList();
            features.Add(new DocsFeature(group.Key.Length == 0 ? NoFeatureTitle : group.Key, featureSlugs[i], specs));
        }

        return features;
    }

    private static string specificationPage(DocsSpecification spec, string pageDirectory, bool attachmentsKept)
    {
        var lines = new List<string> { Marker, "" };
        var attempts = spec.Attempts;
        var latest = attempts[^1];

        lines.AddRange(render(latest, new MarkdownSpecOptions
        {
            HeadingLevel = 1,
            FeatureLink = IndexFileName,
            AttachmentBase = attachmentBase(latest, pageDirectory, attachmentsKept),
            Attempt = attempts.Count,
            Attempts = attempts.Count
        }));

        if (attempts.Count > 1)
        {
            lines.Add("");
            lines.Add("## Earlier attempts");

            for (var i = attempts.Count - 2; i >= 0; i--)
            {
                var attempt = attempts[i];
                lines.Add("");
                lines.Add($"### Attempt {i + 1} of {attempts.Count} — {MarkdownSpecText.Glyph(attempt.Spec)} {attempt.Spec.Verdict}");
                lines.Add("");
                lines.AddRange(render(attempt, new MarkdownSpecOptions
                {
                    IncludeHeading = false,
                    FeatureLink = IndexFileName,
                    AttachmentBase = attachmentBase(attempt, pageDirectory, attachmentsKept),
                    Attempt = i + 1,
                    Attempts = attempts.Count
                }));
            }
        }

        return string.Join("\n", lines) + "\n";
    }

    private static IReadOnlyList<string> render(DocsAttempt attempt, MarkdownSpecOptions options)
    {
        var lines = MarkdownSpecText.Lines(attempt.Spec, options);
        return lines.Count > 0
            ? lines
            : [$"*This specification could not be rendered from {Path.GetFileName(attempt.File.Path) ?? "its results file"}.*"];
    }

    private static string? attachmentBase(DocsAttempt attempt, string pageDirectory, bool attachmentsKept)
        => attachmentsKept && attempt.File.Path is { } path
            ? ResultsPage.AttachmentBase(pageDirectory, Path.GetDirectoryName(path)!)
            : null;

    private static string featureIndex(DocsFeature feature)
    {
        var lines = new List<string>
        {
            Marker,
            "",
            $"# {MarkdownSpecText.Escape(feature.Title)}",
            "",
            $"[All specifications](../{IndexFileName})",
            ""
        };

        foreach (var spec in feature.Specifications)
        {
            var latest = spec.Attempts[^1].Spec;
            var parts = new List<string> { MarkdownSpecText.VerdictSentence(latest) };
            if (latest.DurationMs > 0) parts.Add(MarkdownSpecText.Duration(latest.DurationMs));
            if (spec.Attempts.Count > 1) parts.Add($"{spec.Attempts.Count} attempts");

            lines.Add($"- {MarkdownSpecText.Glyph(latest)} [{MarkdownSpecText.Escape(latest.Title)}]({spec.Slug}.md) — {string.Join(" · ", parts)}");
        }

        return string.Join("\n", lines) + "\n";
    }

    private static string runIndex(IReadOnlyList<ResultsFileContents> files, IReadOnlyList<DocsFeature> features)
    {
        var lines = new List<string> { Marker, "", "# Specifications", "" };

        var suites = files.Select(x => x.Suite).Where(x => x.Length > 0).Distinct(StringComparer.Ordinal).ToList();
        var facts = new List<string>();
        if (suites.Count > 0) facts.Add($"**Suite:** {MarkdownSpecText.Escape(string.Join(", ", suites))}");
        if (files.Count > 0)
        {
            var started = files.Min(x => x.StartedAt);
            if (started != default) facts.Add($"**Run started:** {started.ToUniversalTime():yyyy-MM-dd HH:mm:ss} UTC");
        }

        var branch = files.Select(x => x.Branch).FirstOrDefault(x => !string.IsNullOrEmpty(x));
        if (branch is not null) facts.Add($"**Branch:** {MarkdownSpecText.Escape(branch)}");
        if (files.Count > 1) facts.Add($"**Results files:** {files.Count}");

        if (facts.Count > 0)
        {
            lines.Add(string.Join(" · ", facts));
            lines.Add("");
        }

        var total = features.Sum(f => f.Specifications.Count);
        var passed = features.Sum(f => f.Specifications.Count(s => s.Attempts[^1].Spec.Succeeded));
        var acceptance = features.Sum(f => f.Specifications.Count(s => s.Attempts[^1].Spec.AcceptanceFailing));
        var failed = total - passed - acceptance;

        var summary = $"{total} specification{(total == 1 ? "" : "s")}: {passed} passed, {failed} failed";
        if (acceptance > 0) summary += $", {acceptance} acceptance not yet passing";
        lines.Add(summary);
        lines.Add("");

        lines.Add("| Feature | Specifications | Passed | Failed | Not yet passing |");
        lines.Add("|---|---|---|---|---|");
        foreach (var feature in features)
        {
            var latest = feature.Specifications.Select(s => s.Attempts[^1].Spec).ToList();
            var featurePassed = latest.Count(s => s.Succeeded);
            var featureAcceptance = latest.Count(s => s.AcceptanceFailing);
            lines.Add($"| [{MarkdownSpecText.Cell(feature.Title)}]({feature.Slug}/{IndexFileName}) | {latest.Count} | {featurePassed} | {latest.Count - featurePassed - featureAcceptance} | {featureAcceptance} |");
        }

        return string.Join("\n", lines) + "\n";
    }

    /// <summary>
    /// Every results file inlined, in the shape the HTML results page is handed
    /// (<c>{"files":[{"attachmentBase","results"}]}</c>), so <c>&lt;bobcat-spec&gt;</c> reads it with the
    /// page's own reader. The attachment base is from this file's directory.
    /// </summary>
    private static string foldedResults(IReadOnlyList<ResultsFileContents> files, string outDirectory, bool attachmentsKept)
    {
        var array = new JsonArray();
        foreach (var file in files)
        {
            array.Add(new JsonObject
            {
                ["attachmentBase"] = attachmentsKept && file.Path is { } path
                    ? ResultsPage.AttachmentBase(outDirectory, Path.GetDirectoryName(path)!)
                    : null,
                ["results"] = JsonNode.Parse(File.ReadAllText(file.Path!))
            });
        }

        return new JsonObject { ["files"] = array }.ToJsonString() + "\n";
    }

    /// <summary>Delete the generated Markdown this write did not produce, and the directories that leaves empty.</summary>
    private static IReadOnlyList<string> removeStale(string outDirectory, IReadOnlyList<string> written)
    {
        var kept = new HashSet<string>(written.Select(Path.GetFullPath), StringComparer.Ordinal);
        var removed = new List<string>();

        foreach (var file in Directory.EnumerateFiles(outDirectory, "*.md", SearchOption.AllDirectories))
        {
            var full = Path.GetFullPath(file);
            if (kept.Contains(full)) continue;
            if (!isGenerated(full)) continue;

            File.Delete(full);
            removed.Add(full);
        }

        foreach (var directory in Directory.EnumerateDirectories(outDirectory, "*", SearchOption.AllDirectories)
                     .OrderByDescending(x => x.Length))
        {
            if (!Directory.EnumerateFileSystemEntries(directory).Any()) Directory.Delete(directory);
        }

        return removed;
    }

    private static bool isGenerated(string path)
    {
        try
        {
            using var reader = new StreamReader(path, Encoding.UTF8);
            return reader.ReadLine() == Marker;
        }
        catch (IOException)
        {
            return false;
        }
    }
}

/// <summary>One scenario in one results file.</summary>
internal sealed record DocsAttempt(SpecRender Spec, ResultsFileContents File);

/// <summary>One specification: its identity, its file name, and every attempt at it, oldest first.</summary>
internal sealed record DocsSpecification(string Identity, string Slug, IReadOnlyList<DocsAttempt> Attempts);

internal sealed record DocsFeature(string Title, string Slug, IReadOnlyList<DocsSpecification> Specifications);

/// <summary>What <see cref="ResultsDocs.Write"/> did.</summary>
internal sealed record ResultsDocsOutcome(
    string Directory,
    IReadOnlyList<string> Written,
    IReadOnlyList<string> Removed,
    int Features,
    int Specifications,
    int ResultsFiles)
{
    /// <summary>One line for the terminal.</summary>
    public string Describe()
    {
        var stale = Removed.Count > 0 ? $", {Removed.Count} stale page{(Removed.Count == 1 ? "" : "s")} removed" : "";
        return $"Wrote {Specifications} specification{(Specifications == 1 ? "" : "s")} in {Features} feature{(Features == 1 ? "" : "s")} "
               + $"to {Directory} ({ResultsFiles} results file{(ResultsFiles == 1 ? "" : "s")}{stale})";
    }
}
